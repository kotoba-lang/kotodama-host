#!/usr/bin/env node
// gen-lexicon-nsid.mjs — JUN-133 item 2: lexicon codegen を kotodama-host に移行。
//
// lexicon JSON ルート列を走査し、各 lexicon の id (NSID) と種別
// (query / procedure / record) を抽出、input/output スキーマを最小 TS 型に
// 写像して src/generated/lexicon-nsid-types.ts を生成する。
//
// host capability lexicon はローカルに無いため scripts/lexicon-host-manifest.json
// に形状を pin（プロファイル: 上流が入手できたらこの pin を自動出力に置換）。
//
// Usage:
//   node scripts/gen-lexicon-nsid.mjs --host scripts/lexicon-host-manifest.json \
//        <lexicon-root>... > src/generated/lexicon-nsid-types.ts
//
// zero-dep（node:fs / node:path のみ）。
import fs from "node:fs";
import path from "node:path";

const args = process.argv.slice(2);
let hostManifest = null;
const roots = [];
for (let i = 0; i < args.length; i++) {
  if (args[i] === "--host") { hostManifest = args[++i]; }
  else roots.push(args[i]);
}
if (roots.length === 0) {
  console.error("usage: gen-lexicon-nsid.mjs [--host manifest.json] <lexicon-root>...");
  process.exit(2);
}

// ---- schema → 最小 TS 型の写像（string/number/integer/boolean/array/object/参照） ----
function tsType(schema) {
  if (!schema) return "unknown";
  switch (schema.type) {
    case "string": return "string";
    case "number":
    case "integer": return "number";
    case "boolean": return "boolean";
    case "array": return `${tsType(schema.items)}[]`;
    case "object": return tsInterface(schema);
    default: return "unknown";
  }
}
function tsInterface(schema) {
  if (!schema || schema.type !== "object" || !schema.properties) return "Record<string, unknown>";
  const req = new Set(schema.required || []);
  const lines = Object.entries(schema.properties).map(([k, v]) => {
    const optional = (v && v.optional) || !req.has(k);
    return `  ${JSON.stringify(k)}${optional ? "?" : ""}: ${tsType(v)};`;
  });
  return `{
${lines.join("\n")}
}`;
}

// ---- lexicon 収集 ----
function collectJson(dir, out) {
  for (const ent of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, ent.name);
    if (ent.isDirectory()) collectJson(p, out);
    else if (ent.isFile() && ent.name.endsWith(".json")) out.push(p);
  }
}

function lexiconKind(doc) {
  const t = doc.type;
  if (t === "query" || t === "procedure" || t === "record") return t;
  // defs 内の最初の procedure/query から推定
  const defs = doc.defs || {};
  for (const d of Object.values(defs)) {
    if (d && d.type === "procedure") return "procedure";
    if (d && d.type === "query") return "query";
  }
  return "record";
}

const entries = new Map(); // nsid -> {kind, input, output, source}

if (hostManifest) {
  const man = JSON.parse(fs.readFileSync(hostManifest, "utf8"));
  for (const lex of man.lexicons || []) {
    entries.set(lex.id, {
      kind: lex.type,
      input: { type: "object", properties: shapeToProps(lex.input), required: lex.inputRequired || [] },
      output: { type: "object", properties: shapeToProps(lex.output), required: [] },
      source: "host-manifest-pin",
    });
  }
}
function shapeToProps(shape) {
  const props = {};
  for (const [k, v] of Object.entries(shape || {})) {
    const opt = typeof v === "string" && v.endsWith("?");
    const t = opt ? v.slice(0, -1) : v;
    props[k] = { type: t === "number" ? "number" : t };
    if (opt) props[k].optional = true;
  }
  return props;
}

let scanned = 0;
for (const root of roots) {
  const files = [];
  collectJson(root, files);
  for (const f of files) {
    let doc;
    try { doc = JSON.parse(fs.readFileSync(f, "utf8")); } catch { continue; }
    if (!doc || typeof doc.id !== "string") continue;
    scanned++;
    if (entries.has(doc.id)) continue; // host manifest 優先
    entries.set(doc.id, {
      kind: lexiconKind(doc),
      input: doc.input || doc.defs?.input || null,
      output: doc.output || doc.defs?.output || null,
      source: path.relative(process.cwd(), f),
    });
  }
}

// ---- 生成 ----
const nsids = [...entries.keys()].sort();
const lit = (s) => JSON.stringify(s);
const out = [];
out.push(`// src/generated/lexicon-nsid-types.ts — GENERATED by scripts/gen-lexicon-nsid.mjs.`);
out.push(`// JUN-133 item 2: lexicon codegen を kotodama-host に移行（compat stub 差し替え）。`);
out.push(`//`);
out.push(`// entries: ${nsids.length} NSIDs (scanned ${scanned} lexicon JSON).`);
out.push(`// roots:`);
for (const r of roots) out.push(`//   - ${r}`);
out.push(`// host capability shapes: ${hostManifest ? hostManifest + " (pin — 上流 lexicon 入手後に自動出力へ置換)" : "not provided"}`);
out.push(`//`);
out.push(`// ルール: このファイルは生成物。編集しない。再生成は scripts/gen-lexicon-nsid.mjs。`);
out.push(``);
out.push(`export function nsid<T extends string>(value: T): T {`);
out.push(`  return value;`);
out.push(`}`);
out.push(``);
out.push(`export const LEXICON_NSID = {`);
for (const n of nsids) out.push(`  ${lit(n)}: ${lit(n)},`);
out.push(`} as const;`);
out.push(``);
// ---- 実行時スキーマレジストリ（parseLexiconInput 等が参照） ----
out.push(`export const LEXICON_INPUT_SCHEMA: Record<string, unknown> = {`);
for (const n of nsids) {
  const e = entries.get(n);
  const schema = e.input && e.input.type === "object" && e.input.properties
    ? { type: "object", properties: e.input.properties, required: e.input.required || [] }
    : { type: "object", properties: {}, required: [] };
  out.push(`  ${lit(n)}: ${JSON.stringify(schema)},`);
}
out.push(`};`);
out.push(``);
out.push(`export interface LexiconInputMap {`);
for (const n of nsids) {
  const e = entries.get(n);
  const ty = e.input ? tsInterface(e.input) : "Record<string, unknown>";
  out.push(`  ${lit(n)}: ${ty};`);
}
out.push(`}`);
out.push(``);
out.push(`export interface LexiconOutputMap {`);
for (const n of nsids) {
  const e = entries.get(n);
  const ty = e.output ? tsInterface(e.output) : "Record<string, unknown>";
  out.push(`  ${lit(n)}: ${ty};`);
}
out.push(`}`);
out.push(``);
out.push(`export type LexiconInput<K extends keyof LexiconInputMap> = LexiconInputMap[K];`);
out.push(`export type LexiconOutput<K extends keyof LexiconOutputMap> = LexiconOutputMap[K];`);
out.push(``);
const procs = nsids.filter((n) => entries.get(n).kind === "procedure");
const queries = nsids.filter((n) => entries.get(n).kind === "query");
out.push(`export type KnownLexiconProcedureNSID = ${procs.map(lit).join(" | ") || "never"};`);
out.push(`export type KnownLexiconQueryNSID = ${queries.map(lit).join(" | ") || "never"};`);
out.push(``);
process.stdout.write(out.join("\n") + "\n");
